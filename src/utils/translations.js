export const generateFunnyTitle = (items, spent, isHighestSpender) => {
  const itemNames = items.map(i => i.toLowerCase()).join(' ');
  if (isHighestSpender && spent > 0) return "👑 The Big Spender";
  if (itemNames.includes('pizza') || itemNames.includes('burger')) return "🍕 Fast Food Enthusiast";
  if (itemNames.includes('beer') || itemNames.includes('drink') || itemNames.includes('coffee')) return "☕ Beverage Lover";
  if (spent === 0) return "👻 The Phantom Splitter";
  return "⚡ Smart Saver";
};